"""评论的敏感词拦截：命中任意一个词就不让发。

评论是「先发后审」，没有人工把关，所以用一份很短的词表挡住最明显的辱骂、黄赌和黑产广告。
帖子不走这里：帖子有管理员逐条审核。

维护方法：直接增删下面的词。词表故意保持很短，只放几乎不可能误伤正常聊天的词；
像「加微信」「兼职」这种正常场景也会用到的词不要放进来，交给举报处理。
"""

BANNED_WORDS: tuple[str, ...] = (
    # 辱骂
    "傻逼", "煞笔", "草泥马", "操你妈", "去死吧", "死全家", "滚你妈",
    # 黄赌毒
    "约炮", "裸聊", "援交", "博彩", "赌球", "冰毒",
    # 黑产广告
    "刷单", "代考", "代写论文", "办假证", "套现",
)


def find_banned(text: str) -> str | None:
    """返回命中的第一个敏感词；没有命中返回 None。比较前去掉空白，防止用空格隔开来绕过。"""
    compact = "".join(text.split()).lower()
    return next((w for w in BANNED_WORDS if w in compact), None)
